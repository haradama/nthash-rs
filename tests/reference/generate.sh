#!/usr/bin/env bash
# Regenerate tests/reference/vectors.txt from the C++ reference implementation.
#
#   tests/reference/generate.sh            # rewrite vectors.txt in place
#   tests/reference/generate.sh --check    # fail if vectors.txt is out of date
#
# Needs git and a C++17 compiler ($CXX, default c++). The reference is fetched
# at the pinned commit below; set NTHASH_REFERENCE_DIR to use an existing
# checkout instead (it is used as is, so make sure it is at the right commit).
set -euo pipefail

REFERENCE_REPO="https://github.com/bcgsc/ntHash"
REFERENCE_COMMIT="4e8a73685173ed1916a2aa7bd6ea6932be93cd5a"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

ref="${NTHASH_REFERENCE_DIR:-}"
if [ -z "$ref" ]; then
  ref="$work/ntHash"
  git init -q "$ref"
  git -C "$ref" fetch -q --depth 1 "$REFERENCE_REPO" "$REFERENCE_COMMIT"
  git -C "$ref" checkout -q FETCH_HEAD
fi

# The reference's src/internal.hpp uses uint64_t without including <cstdint>,
# which newer standard libraries no longer pull in transitively.
"${CXX:-c++}" -std=c++17 -O1 -include cstdint -I "$ref/include" \
  "$here/gen_vectors.cpp" "$ref/src/kmer.cpp" "$ref/src/seed.cpp" \
  -o "$work/gen_vectors"

{
  echo "# Reference vectors produced by the C++ ntHash library."
  echo "# Source: $REFERENCE_REPO at commit $REFERENCE_COMMIT"
  echo "# Generated by tests/reference/generate.sh — do not edit by hand."
  # The reference warns on stderr about asymmetric seeds; those are intended here.
  "$work/gen_vectors" 2>/dev/null
} > "$work/vectors.txt"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$work/vectors.txt" "$here/vectors.txt"; then
    echo "tests/reference/vectors.txt does not match the C++ reference output." >&2
    diff "$here/vectors.txt" "$work/vectors.txt" | head -20 >&2 || true
    exit 1
  fi
  echo "vectors.txt matches the C++ reference."
else
  cp "$work/vectors.txt" "$here/vectors.txt"
  echo "wrote $here/vectors.txt"
fi
